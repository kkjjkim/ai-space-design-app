// 카테고리 순서를 고정해 목록을 묶는다 (매번 순서가 바뀌면 색인에도 안 좋다).
export function getAnswersByCategory(): { category: string; answers: Answer[] }[] {
  return ANSWER_CATEGORIES.map((category) => ({
    category,
    answers: ANSWERS.filter((a) => a.category === category),
  })).filter((g) => g.answers.length > 0);
}

// 구조화 데이터·llms.txt 에 넣을 답변 본문(평문).
// 짧은 답 + 각 절의 내용을 이어 붙인다. 답변 엔진은 이 텍스트를 읽는다.
export function answerPlainText(a: Answer): string {
  const lines: string[] = [a.shortAnswer];
  for (const section of a.sections) {
    lines.push(`【${section.heading}】`);
    for (const block of section.blocks) {
      if (block.type === "text") lines.push(block.body);
      if (block.type === "list") lines.push(...block.items.map((i) => `- ${i}`));
      if (block.type === "steps")
        lines.push(...block.items.map((i, n) => `${n + 1}. ${i}`));
      if (block.type === "table")
        lines.push(...block.rows.map(([k, v]) => `- ${k}: ${v}`));
    }
  }
  return lines.join("\n");
}
